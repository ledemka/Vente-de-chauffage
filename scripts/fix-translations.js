// Generic function to replace values that end with " (EN)", " (DE)", etc.
function fixDict(obj, langCode) {
    for (let k in obj) {
        if (typeof obj[k] === 'string' && obj[k].endsWith(` (${langCode.toUpperCase()})`)) {
            let frText = obj[k].replace(` (${langCode.toUpperCase()})`, '');
            obj[k] = translateText(frText, langCode);
        } else if (typeof obj[k] === 'object' && obj[k] !== null) {
            fixDict(obj[k], langCode);
        }
    }
}

