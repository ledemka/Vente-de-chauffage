function processLang(obj, frObj, langCode) {
    for (let k in frObj) {
        if (allowlist.includes(k) || k.startsWith('emails.')) continue;
        if (typeof frObj[k] === 'string' && obj[k] === frObj[k]) {
            if (map[langCode][frObj[k]]) {
                obj[k] = map[langCode][frObj[k]];
            }
        } else if (typeof frObj[k] === 'object' && frObj[k] !== null) {
            processLang(obj[k], frObj[k], langCode);
        }
    }
}

